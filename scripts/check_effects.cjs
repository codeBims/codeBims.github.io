const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const source = fs.readFileSync(require('node:path').join(__dirname,'../effects-policy.js'),'utf8');
function setup({reduced=false,saved=null,storageFails=false}={}) {
  const system = new EventTarget(); system.matches = reduced;
  const window = new EventTarget(), handlers = {}, writes = [];
  const select = {value:'auto',attributes:{},setAttribute(k,v){this.attributes[k]=v;},addEventListener(k,v){handlers[k]=v;}};
  const document = {documentElement:{lang:'id',dataset:{}},querySelectorAll:()=>[select]};
  const localStorage = {getItem(){if(storageFails)throw Error('denied');return saved;},setItem(k,v){if(storageFails)throw Error('denied');writes.push([k,v]);}};
  vm.runInNewContext(source,{matchMedia:()=>system,window,document,localStorage,Event,EventTarget});
  const choose = value => {select.value=value;handlers.change();};
  return {system,window,select,document,writes,choose,policy:window.PortfolioEffects};
}
// A deliberate site-level choice must work on a device that reduces motion.
const explicit=setup({reduced:true,saved:'full'});
assert.equal(explicit.policy.media.matches,false,'Full effects must be available on a reduced-motion device');
assert.equal(explicit.document.documentElement.dataset.effects,'active');
const device=setup({reduced:true});
assert.equal(device.policy.media.matches,true);
assert.equal(device.policy.interaction,'fade');
assert.equal(device.select.value,'auto');
assert.equal(device.document.documentElement.dataset.effects,'reduced');
let changes=0;device.policy.media.addEventListener('change',()=>changes++);
device.choose('full');assert.equal(device.policy.media.matches,false);
assert.equal(device.policy.interaction,'full');
assert.deepEqual(device.writes[0],['portfolio-effects','full']);
device.choose('paused');assert.equal(device.policy.media.matches,true);
assert.equal(device.policy.interaction,'none');
assert.equal(device.document.documentElement.dataset.effects,'paused');
device.choose('auto');assert.equal(device.policy.interaction,'fade');
device.system.matches=false;device.system.dispatchEvent(new Event('change'));
assert.equal(device.policy.media.matches,false);assert.equal(changes,4);
device.document.documentElement.lang='en';device.window.dispatchEvent(new Event('portfolio-language-change'));
assert.equal(device.select.attributes['aria-label'],'Animation');
assert.match(device.select.title,/device/i);
assert.equal(setup({saved:'paused'}).policy.interaction,'none');
assert.equal(setup({saved:'invalid',reduced:true}).select.value,'auto');
const denied=setup({storageFails:true,reduced:true});denied.choose('full');
assert.equal(denied.policy.media.matches,false);
console.log('PASS: device default, full opt-in, pause, preference changes, persistence, language and denied storage');
